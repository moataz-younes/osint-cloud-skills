def main() -> None:
    # remove old monolithic library if present
    old = SKILLS / "library.json"
    if old.exists():
        old.unlink()

    catalog = {"name": "OSINT Skills Library", "version": "2.0.0", "sections": []}
    total = 0
    for section_id, meta in SECTIONS.items():
        section_dir = SKILLS / section_id
        section_dir.mkdir(parents=True, exist_ok=True)
        skills = LIBRARY[section_id]
        # clean old json files in section
        for p in section_dir.glob("*.json"):
            p.unlink()
        for s in skills:
            s = dict(s)
            s["section"] = section_id
            path = section_dir / f"{s['id']}.json"
            path.write_text(json.dumps(s, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        index = {
            "id": section_id,
            "title": meta["title"],
            "description": meta["description"],
            "skill_count": len(skills),
            "skills": [s["id"] for s in skills],
        }
        (section_dir / "_section.json").write_text(
            json.dumps(index, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        catalog["sections"].append(
            {
                "id": section_id,
                "title": meta["title"],
                "description": meta["description"],
                "path": f"skills/{section_id}",
                "skill_count": len(skills),
            }
        )
        total += len(skills)

    catalog["skill_count"] = total
    (SKILLS / "catalog.json").write_text(
        json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"Generated {total} skills across {len(SECTIONS)} sections")


if __name__ == "__main__":
    main()
